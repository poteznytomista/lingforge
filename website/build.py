#!/usr/bin/env python3
"""Build the Pages artifact, verifying the public release before deployment.

Only Python's standard library is required. Local preview serves website/ directly.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import urllib.request

ROOT = Path(__file__).resolve().parent


def verify_stream(stream, release):
    digest = hashlib.sha256()
    total = 0
    while chunk := stream.read(1024 * 1024):
        total += len(chunk)
        if total > release["bytes"]:
            raise ValueError("Download exceeds the declared release size")
        digest.update(chunk)
    if total != release["bytes"] or digest.hexdigest() != release["sha256"]:
        raise ValueError("AppImage size/checksum does not match release.json")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", required=True, help="GitHub OWNER/REPOSITORY")
    parser.add_argument("--verify-release", action="store_true", help="Download and hash the public release before building")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9_.-]+", args.repository) or args.repository.split("/")[1] in {".", ".."}:
        parser.error("Repository must be OWNER/REPOSITORY, without URLs or spaces")
    release = json.loads((ROOT / "release.json").read_text())
    if not re.fullmatch(r"\d+\.\d+\.\d+", release["version"]):
        raise ValueError("Expected a three-part release version")
    if release["tag"] != "v" + release["version"] or release["filename"] != f'LingForge_{release["version"]}_amd64.AppImage':
        raise ValueError("Release tag/filename/version disagree")
    if type(release["bytes"]) is not int or not 0 < release["bytes"] < 2 * 1024**3 or not re.fullmatch(r"[a-f0-9]{64}", release["sha256"]):
        raise ValueError("Invalid release size/checksum")
    source = (ROOT / "index.html").read_text()
    local_url = "downloads/" + release["filename"]
    for expected in [f'v{release["version"]}', local_url, release["sha256"], f'{release["bytes"] / 1024**2:.2f} MiB']:
        if expected not in source:
            raise ValueError(f"Update the visible release details in index.html: missing {expected}")
    url = f'https://github.com/{args.repository}/releases/download/{release["tag"]}/{release["filename"]}'
    if args.verify_release:
        # No token: a visitor must be able to download these bytes publicly.
        with urllib.request.urlopen(url, timeout=120) as response:
            verify_stream(response, release)
        print("Public release download verified against SHA-256 and byte count.")
    else:
        local = ROOT / "downloads" / release["filename"]
        if local.is_symlink():
            raise ValueError("Expected a regular local AppImage, not a symlink")
        with local.open("rb") as stream:
            verify_stream(stream, release)
        print("Local AppImage verified. Remote release availability NOT checked.")
    output = ROOT / "_site"
    # Only remove our own previous generated output. Never overwrite arbitrary data.
    marker = output / ".lingforge-site-output"
    if output.is_symlink() or (output.exists() and not marker.is_file()):
        raise ValueError("Refusing to replace an unrecognized _site directory")
    if output.exists():
        shutil.rmtree(output)
    output.mkdir()
    marker.write_text("Generated by website/build.py\n")
    for name in ["styles.css", "app.js", "launch-help.html", "notices.html", "release.json", "checksums.txt"]:
        shutil.copy2(ROOT / name, output / name)
    shutil.copytree(ROOT / "assets", output / "assets")
    # Relative assets work on both username.github.io/repository/ and custom domains.
    (output / "index.html").write_text(source.replace(f'href="{local_url}"', f'href="{url}"'))
    (output / ".nojekyll").touch()
    (output / "checksums.txt").write_text(f'{release["sha256"]}  {release["filename"]}\n')
    print(f"Built {output}; downloads point to {url}")


if __name__ == "__main__":
    main()
